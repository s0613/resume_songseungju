/**
 * 카테고리 slug에 해당하는 글.
 * 모르는 slug는 전체로 취급한다.
 */
export function postsInCategory(slug: string): BlogPost[] {
    const normalizedSlug = normalizeCategorySlug(slug)
    const target = CATEGORY_NODES.find((cat) => cat.slug === normalizedSlug)
    if (!target || target.slug === "all") return posts
    return posts.filter((post) => post.category === target.name)
}

// 글 수는 손으로 세지 않고 posts에서 뽑는다 — 글을 추가해도 어긋나지 않는다.
export const categories: Category[] = CATEGORY_NODES.map((cat) => ({
    ...cat,
    count: postsInCategory(cat.slug).length,
}))

export function getPost(slug: string): BlogPost | undefined {
    return posts.find((p) => p.slug === slug)
}

/** 글 본문의 첫 이미지 블록 — 목록 대표(뉴스형) 카드의 썸네일로 쓴다. 없으면 null. */
export function getPostThumbnail(
    post: BlogPost
): Extract<BlogBlock, { type: "image" }> | null {
    for (const block of post.blocks) {
        if (block.type === "image") return block
    }
    return null
}
